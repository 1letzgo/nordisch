/// A map object. x = east, z = north (metres from the area centre), yaw clockwise from north.
/// New objects have `genId == nil`; objects generated by the importer carry their id and can be
/// moved/rotated/scaled/deleted (saved as "changes"). For those `scale` is relative to `baseSize`.
struct PlacedObject: Codable, Identifiable, Equatable {
    var id = UUID()
    var type: String
    var x: Double
    var z: Double
    var yaw: Double = 0
    var scale: Double = 1
    var seed: Int = Int.random(in: 0..<100_000)
    var genId: String? = nil
    var baseSize: Double = 1
    var deleted = false

    var isGenerated: Bool { genId != nil }
    /// Size relative to the type's default footprint.
    var effScale: Double { scale * baseSize }

    init(type: String, x: Double, z: Double) {
        self.type = type
        self.x = x
        self.z = z
    }

    enum CodingKeys: String, CodingKey { case id, type, x, z, yaw, scale, seed }

    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(id, forKey: .id)
        try c.encode(type, forKey: .type)
        try c.encode(x, forKey: .x)
        try c.encode(z, forKey: .z)
        try c.encode(yaw, forKey: .yaw)
        try c.encode(scale, forKey: .scale)
        try c.encode(seed, forKey: .seed)
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = (try? c.decode(UUID.self, forKey: .id)) ?? UUID()
        type = try c.decode(String.self, forKey: .type)
        x = try c.decode(Double.self, forKey: .x)
        z = try c.decode(Double.self, forKey: .z)
        yaw = try c.decodeIfPresent(Double.self, forKey: .yaw) ?? 0
        scale = try c.decodeIfPresent(Double.self, forKey: .scale) ?? 1
        seed = try c.decodeIfPresent(Int.self, forKey: .seed) ?? 0
    }

    var kind: ObjectType { ObjectType.find(type) }

    func with(id: UUID) -> PlacedObject {
        var c = self
        c.id = id
        return c
    }

    /// Local (east, north) offset rotated by yaw – same convention as Unity's Quaternion.Euler(0, yaw, 0).
    func world(_ lx: Double, _ lz: Double) -> CGPoint {
        let a = yaw * .pi / 180
        return CGPoint(x: x + (lx * cos(a) + lz * sin(a)) * effScale, y: z + (-lx * sin(a) + lz * cos(a)) * effScale)
    }

    func toLocal(_ p: CGPoint) -> CGPoint {
        let a = yaw * .pi / 180
        let dx = (p.x - x) / effScale, dz = (p.y - z) / effScale
        return CGPoint(x: dx * cos(a) - dz * sin(a), y: dx * sin(a) + dz * cos(a))
    }

    func contains(_ p: CGPoint, slack: Double) -> Bool {
        let l = toLocal(p)
        let s = slack / effScale
        switch kind.shape {
        case .circle(let r): return (l.x * l.x + l.y * l.y).squareRoot() <= r + s
        case .rect(let w, let d): return abs(l.x) <= w / 2 + s && abs(l.y) <= d / 2 + s
        }
    }
}

/// Data/<area>.edits.json (read by Assets/Editor/OsmImport/EditsPlacer.cs).
struct EditsFile: Codable {
    var version = 2
    var area: String
    var objects: [PlacedObject]
    var changes: [String: Change]?

    struct Change: Codable {
        var x: Double?
        var z: Double?
        var yaw: Double?
        var scale: Double?
        var deleted: Bool?
    }
}

/// Assets/Generated/<area>/<area>_objects.json – everything the importer placed.
struct GeneratedFile: Decodable {
    struct Record: Decodable {
        let id: String
        let type: String
        let x: Double
        let z: Double
        let yaw: Double
        let size: Double
    }
    let objects: [Record]
}

/// Entry of Tools/osm/areas.json.
struct Area: Identifiable, Hashable, Decodable {
    let id: String
    let name: String
    let lat: Double
    let lon: Double
    let size_m: Double
    /// Optional non-square area: metres from the centre in each direction (areas.json "extent").
    let extent: Extent?

    struct Extent: Hashable, Decodable { let west, east, south, north: Double }

    /// Playable rectangle in local metres (x east, y north) – same as the importer's AreaRect.
    var rect: CGRect {
        if let e = extent { return CGRect(x: -e.west, y: -e.south, width: e.west + e.east, height: e.south + e.north) }
        return CGRect(x: -size_m / 2, y: -size_m / 2, width: size_m, height: size_m)
    }
}

