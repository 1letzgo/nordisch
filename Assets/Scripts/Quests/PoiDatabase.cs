using System.Collections.Generic;
using UnityEngine;

namespace LeGamez.Quests
{
    public enum PoiCategory
    {
        Landmark,
        Museum,
        Church,
        Monument,
        Viewpoint,
        Artwork,
        Lighthouse,
        Nature,
        Culture,
    }

    [System.Serializable]
    public class PoiEntry
    {
        public string id;          // stable: "<osmType>/<osmId>"
        public string name;
        public PoiCategory category;
        public Vector3 position;   // world space, ground level
        public double lat, lon;
    }

    /// <summary>Points of interest of one area, generated by the OSM importer.</summary>
    [CreateAssetMenu(menuName = "LeGamez/POI Database")]
    public class PoiDatabase : ScriptableObject
    {
        public List<PoiEntry> entries = new List<PoiEntry>();
    }
}
